import { describe, it, expect } from "vitest";
import { ScannerResultSchema } from "../lib/schemas/scanner";
import { SmartReviewResultSchema } from "../lib/schemas/review";
import { CopilotResultSchema } from "../lib/schemas/copilot";
import { ImpactInsightsResultSchema } from "../lib/schemas/insights";
import { CommunicationDraftResultSchema } from "../lib/schemas/drafts";

describe("Phase 4 AI Schema Validation", () => {
  it("validates ScannerResultSchema structure and safety disclaimer requirement", () => {
    const validData = {
      visibleFoodItems: ["Rice & Lentil Curry", "Chapatis"],
      estimatedFoodCategory: "cooked_meals",
      visiblePackaging: "sealed_containers",
      containerCondition: "closed_and_covered",
      visibleLabels: ["Prepared 12:30 PM"],
      explicitlyReadableQuantity: "50 portions",
      uncertainObservations: ["Internal temperature cannot be assessed visually"],
      clarificationQuestions: ["Was the food held above 65°C?"],
      suggestedDietaryCategory: "vegetarian",
    };

    const parsed = ScannerResultSchema.parse(validData);
    expect(parsed.visibleFoodItems).toContain("Rice & Lentil Curry");
    expect(parsed.estimatedFoodCategory).toBe("cooked_meals");
    expect(parsed.visiblePackaging).toBe("sealed_containers");
    expect(parsed.safetyDisclaimer).toContain("Visual analysis cannot determine microbial safety");
  });

  it("validates SmartReviewResultSchema structure and findings", () => {
    const validReview = {
      overallStatus: "needs_attention",
      findings: [
        {
          severity: "warning",
          fieldName: "pickupWindowEnd",
          title: "Tight pickup window",
          description: "Pickup window closes within 45 minutes of preparation.",
          evidence: "Window end is 13:15, prep time 12:30",
          suggestedAction: "Extend window if storage allows.",
        },
      ],
      suggestedQuestions: ["Can the food be held in warm storage until 14:00?"],
    };

    const parsed = SmartReviewResultSchema.parse(validReview);
    expect(parsed.overallStatus).toBe("needs_attention");
    expect(parsed.findings).toHaveLength(1);
    expect(parsed.findings[0].severity).toBe("warning");
    expect(parsed.disclaimer).toContain("AI Smart Review identifies data ambiguities");
  });

  it("validates CopilotResultSchema structure and grounding IDs", () => {
    const validCopilot = {
      summary: "Surplus Food Overview",
      answer: "We currently have 180 portions available from Greenfield College Canteen.",
      referencedRecordIds: ["demo-don-greenfield", "demo-rec-a"],
      actionableSuggestions: ["Navigate to matching engine"],
      limitations: ["Based strictly on current in-memory records"],
    };

    const parsed = CopilotResultSchema.parse(validCopilot);
    expect(parsed.referencedRecordIds).toContain("demo-don-greenfield");
    expect(parsed.summary).toBe("Surplus Food Overview");
    expect(parsed.actionableSuggestions).toHaveLength(1);
  });

  it("validates ImpactInsightsResultSchema structure", () => {
    const validInsights = {
      executiveSummary: "Food rescue operations achieved an 88% overall allocation rate.",
      demandPatterns: ["High demand for hot meals in Sector 62."],
      bottlenecksIdentified: ["Volunteer driver availability between 14:00 and 16:00."],
      actionableRecommendations: ["Pre-alert shelters with flexible receiving hours."],
      dataGroundedEvidence: ["180 of 180 portions matched to 3 organizations"],
    };

    const parsed = ImpactInsightsResultSchema.parse(validInsights);
    expect(parsed.demandPatterns).toHaveLength(1);
    expect(parsed.bottlenecksIdentified).toHaveLength(1);
    expect(parsed.actionableRecommendations).toHaveLength(1);
    expect(parsed.disclaimer).toContain("simulated prototype records");
  });

  it("validates CommunicationDraftResultSchema structure", () => {
    const validDraft = {
      subject: "Urgent: Food Surplus Pickup Scheduled",
      body: "Hello Team, we have reserved 80 portions of fresh food for pickup today at 14:30.",
      language: "english",
      targetAudience: "recipient",
      disclaimer: "Draft generated by FoodRelay AI. Review before sending.",
    };

    const parsed = CommunicationDraftResultSchema.parse(validDraft);
    expect(parsed.language).toBe("english");
    expect(parsed.targetAudience).toBe("recipient");
  });
});
